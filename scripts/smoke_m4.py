#!/usr/bin/env python
"""Milestone 4 smoke gate - the BUILD_PLAN section 3 / spec 13.4 definition of done.

Gate scope (offline, end to end, per the M4 tasking - the three §6.6
durability behaviors that M4 tasks 4.3/4.4/4.5 built, pinned through the real
HTTP flow on persisted state):

    1. RESUME: simulate a server restart by abandoning the running app
       mid-job and reopening the job engine on the persisted state - a fresh
       create_app() over the same projects root, then resume(). The old
       engine's worker is left blocked inside beat 2's provider call exactly
       like a dead process (the call never returns and the engine is never
       stopped). The restart must complete the job WITHOUT redoing any asset:
       beat 1's artifacts stay byte-identical with attempts == 1, the stuck
       ``generating`` beat 2 resets to ``pending`` and finishes exactly once,
       only beats 2-3 are generated by the new engine, spend is not
       double-counted (spend_log.jsonl carries exactly one line per asset -
       the beat-1 line written by the old app survives the restart), and a
       job left ``awaiting_confirmation`` is NOT resumed - it stays for the
       user to re-drive;
    2. PER-ASSET RETRY: a non-retryable provider failure on beat 2's image
       leaves the job ``partial`` with every other asset done; POST
       /api/jobs/{id}/assets/{asset_id}/retry (the BUILD_PLAN 4.4 JSON
       mutation) regenerates ONLY the failed asset - beats 1 and 3 see exactly
       one provider call each across the whole run and their artifacts stay
       byte-identical - and the job lands ``completed`` with all 3 slides
       exported;
    3. SPEND CAP: a priced job whose next call would cross the hard cap ends
       ``partial`` with the completed assets kept - beats 1-2 finish with the
       spend landing exactly ON the cap (allowed), beats 3-4 are skipped
       BEFORE any paid call with errors naming the cap, the provider is
       dialed exactly twice, the kept beats' deliverables are exported, and
       the cap + confirmed estimate travel into the job payload.

Everything runs over the real HTTP app (FastAPI TestClient - no server) on
mock-shaped scripted providers registered under the ``mock`` provider id:
they write real WAV/PNG media (inherited from the BUILD_PLAN 1.4 mocks) so
local assembly is real ffmpeg, while failures/blocks/prices are scripted per
check. The confirm-before-spend gate is exercised for real: every job is
estimated, carried to ``awaiting_confirmation``, and confirmed before the
worker starts.

Offline guarantees (gate requirement: ZERO real network, asserted not assumed):
- a process-wide socket guard records - and fails the run on - ANY outbound
  attempt (connect, connect_ex, create_connection, getaddrinfo,
  gethostbyname). The only traffic allowed through, always disclosed in the
  report, is the interpreter's own asyncio ``socket.socketpair`` self-pipe
  (loopback wakeup plumbing every TestClient portal needs on Windows) and
  address-literal resolvers that never touch DNS;
- the apps boot on key-less temp key stores with the scripted mock-id
  providers - there is no provider client that could dial anything;
- the cap check's prices live in the scripted provider's own quote, never in
  a networked API.

Usage:  .venv/Scripts/python.exe scripts/smoke_m4.py
Exit:   0 - every check passed (gate green); 1 - at least one check failed.

The gate runs against a throwaway projects root + key stores (a temp dir), so
it is idempotent and leaves nothing behind.
"""

