def _provider_error(message: str) -> Any:
    from app.engines.base import ProviderError

    return ProviderError("mock", message, retryable=False)


def _asset_key(out_path: Path) -> str:
    """'<project slug>/<file name>' - beats of different projects are distinct."""
    return f"{out_path.parent.parent.name}/{out_path.name}"


class ScriptedTTS:
    """The BUILD_PLAN 1.4 mock TTS with a script: provider_id 'mock', real
    silent WAVs (assembly is real ffmpeg), every call recorded, optional
    non-retryable first-call failures, and an optional beat whose call enters
    and blocks forever - the dead server's in-flight request."""

    provider_id = "mock"

    def __init__(self) -> None:
        self.calls: list[str] = []  # every generate() entry, in call order
        self.completed: list[str] = []  # calls that returned a result
        self.fail_first: dict[str, int] = {}
        self.block_on: dict[str, threading.Event] = {}

    def fail_once(self, out_path: Path) -> None:
        self.fail_first[_asset_key(out_path)] = 1

    def block_beat(self, out_path: Path) -> threading.Event:
        entered = threading.Event()
        self.block_on[_asset_key(out_path)] = entered
        return entered

    def generate(self, request: Any) -> Any:
        key = _asset_key(request.out_path)
        self.calls.append(key)
        entered = self.block_on.get(key)
        if entered is not None:
            entered.set()
            BLOCK_FOREVER.wait()  # a dead server's call never returns
        left = self.fail_first.get(key, 0)
        if left:
            self.fail_first[key] = left - 1
            raise _provider_error(FAILURE_MESSAGE)
        from app.engines.mocks import MockTTSProvider

        result = MockTTSProvider.generate(self, request)  # real silent WAV
        self.completed.append(key)
        return result

    def estimate_cost_usd(self, request: Any) -> float:
        return 0.0


class ScriptedImage:
    """The BUILD_PLAN 1.4 mock image provider with a script: provider_id
    'mock', real deterministic PNGs, every call recorded, optional
    non-retryable first-call failures, and its own per-image price quote
    (0 for dry-run jobs; the cap check quotes ASSET_PRICE_USD)."""

    provider_id = "mock"

    def __init__(self, price_usd: float = 0.0) -> None:
        self.price_usd = float(price_usd)
        self.calls: list[str] = []  # every generate() entry, in call order
        self.completed: list[str] = []  # calls that returned a result
        self.fail_first: dict[str, int] = {}

    def fail_once(self, out_path: Path) -> None:
        self.fail_first[_asset_key(out_path)] = 1

    def generate(self, request: Any) -> Any:
        key = _asset_key(request.out_path)
        self.calls.append(key)
        left = self.fail_first.get(key, 0)
        if left:
            self.fail_first[key] = left - 1
            raise _provider_error(FAILURE_MESSAGE)
        from app.engines.mocks import MockImageProvider

        result = MockImageProvider.generate(self, request)  # real deterministic PNG
        self.completed.append(key)
        return result

    def estimate_cost_usd(self, request: Any) -> float:
        return self.price_usd


