def _fail(message: str) -> None:
    raise AssertionError(message)


def _tail(exc: BaseException, lines: int = 5) -> str:
    chunks = traceback.format_exception(type(exc), exc, exc.__traceback__)
    rows = [row for chunk in chunks for row in chunk.splitlines() if row.strip()]
    return "\n".join("        " + row for row in rows[-lines:])


def script_of(beats: tuple[str, ...]) -> str:
    return "\n\n".join(beats) + "\n"


# --- app/flow helpers -------------------------------------------------------------


def build_app(ctx: dict[str, Any], name: str, tts: ScriptedTTS, image: ScriptedImage) -> Any:
    """One 'server process': scripted providers under the mock id, a throwaway
    key store (recorded for the audit), no maintenance thread, persisted job
    engine + real assembler over the shared throwaway projects root."""
    registry = ctx["Registry"]()
    registry.register("tts", tts)
    registry.register("image", image)
    store = ctx["KeyStore"](
        ctx["workspace"] / f"keys-{name}" / ctx["KEYS_FILENAME"],
        provider_engines={pid: info.engines for pid, info in ctx["PROVIDERS"].items()},
        engines=ctx["ENGINES"],
    )
    if store.configured_providers():
        _fail("a fresh key store must start empty - this gate uses no keys at all")
    app = ctx["create_app"](
        registry=registry,
        key_store=store,
        projects_root=ctx["projects_root"],
        maintenance_enabled=False,
    )
    ctx["key_stores"][name] = store
    return app


def client_of(app: Any) -> Any:
    """A request client for one app instance. The lifespan is never entered
    (no maintenance thread exists) - the job engine already runs from
    create_app; the dead-server app is simply never talked to again."""
    from fastapi.testclient import TestClient

    return TestClient(app)


def run_flow(
    ctx: dict[str, Any],
    client: Any,
    project: str,
    beats: tuple[str, ...],
    *,
    confirm: bool = True,
    extra_options: dict[str, str] | None = None,
) -> str:
    """The user path: input -> options (job created + estimated) -> confirm."""
    resp = client.post(
        "/input", data={"project": project, "script": script_of(beats)}, follow_redirects=False
    )
    if resp.status_code != 303:
        _fail(f"POST /input ({project}) -> {resp.status_code}")
    options = {
        **PORTRAIT,
        "audio": "on",
        "visual": "images",
        "dry_run": "on",
        **(extra_options or {}),
    }
    resp = client.post("/options", data=options, follow_redirects=False)
    if resp.status_code != 303 or not resp.headers["location"].startswith("/confirm/"):
        _fail(f"POST /options ({project}) -> {resp.status_code} {resp.headers.get('location')!r}")
    job_id = resp.headers["location"].rsplit("/", 1)[1]
    if confirm:
        resp = client.post(f"/jobs/{job_id}/confirm", follow_redirects=False)
        if resp.status_code != 303:
            _fail(f"confirming job {job_id} failed -> {resp.status_code}")
    return job_id


def get_job(client: Any, job_id: str) -> dict[str, Any]:
    resp = client.get(f"/api/jobs/{job_id}")
    if resp.status_code != 200:
        _fail(f"GET /api/jobs/{job_id} -> {resp.status_code}")
    return resp.json()


def wait_for(
    client: Any,
    job_id: str,
    predicate: Callable[[dict[str, Any]], bool],
    what: str,
    timeout: float,
) -> dict[str, Any]:
    deadline = time.monotonic() + timeout
    payload: dict[str, Any] = {}
    while time.monotonic() < deadline:
        payload = get_job(client, job_id)
        if predicate(payload):
            return payload
        time.sleep(POLL_S)
    states = [(a["kind"], a["beat_index"], a["status"]) for a in payload.get("assets", [])]
    raise AssertionError(
        f"job {job_id} never {what} within {timeout:.0f}s"
        f" (status {payload.get('status')!r}, assets {states})"
    )


def asset_row(payload: dict[str, Any], kind: str, beat: int) -> dict[str, Any]:
    for asset in payload["assets"]:
        if asset["kind"] == kind and asset["beat_index"] == beat:
            return asset
    _fail(f"job {payload['id']} has no {kind} asset for beat {beat}")


def statuses_of(payload: dict[str, Any]) -> list[tuple[str, int, str]]:
    return [(a["kind"], a["beat_index"], a["status"]) for a in payload["assets"]]


def slug_of(ctx: dict[str, Any], project: str) -> str:
    return ctx["slugify"](project)


def spend_log_rows(ctx: dict[str, Any], slug: str) -> list[dict[str, Any]]:
    log = ctx["projects_root"] / slug / "state" / "spend_log.jsonl"
    if not log.is_file():
        return []
    rows = []
    for line in log.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def one_spend_line_per_asset(ctx: dict[str, Any], slug: str, final: dict[str, Any]) -> list[dict]:
    """spend_log.jsonl carries exactly one line per asset of the job - the
    no-double-count pairing across any restart/retry."""
    rows = spend_log_rows(ctx, slug)
    logged = sorted(r.get("asset_id") for r in rows)
    if logged != sorted(a["id"] for a in final["assets"]):
        _fail(f"{slug}: spend log must carry exactly one line per asset, got {logged}")
    return rows


