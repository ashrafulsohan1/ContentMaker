def check_environment(ctx: dict[str, Any]) -> str:
    """Python >= 3.11, ffmpeg + ffprobe present, the app + its durability seams
    import, and platforms.json carries exactly the spec this gate pins."""
    py = ".".join(map(str, sys.version_info[:3]))
    # Deliberate runtime guard (gate may run under any interpreter): noqa - the
    # toolchain targets 3.11+, but this check must survive when it doesn't.
    if sys.version_info < (3, 11):  # noqa: UP036
        _fail(f"python {py} is below the app's minimum 3.11")
    for tool in ("ffmpeg", "ffprobe"):
        if shutil.which(tool) is None:
            _fail(f"{tool} not on PATH - assembly cannot run (see scripts/check_env.py)")
        proc = subprocess.run([tool, "-version"], capture_output=True, text=True, timeout=30)
        if proc.returncode != 0:
            _fail(f"{tool} -version failed: {(proc.stderr or '').strip()[:200]}")
    try:
        import importlib

        ctx["create_app"] = importlib.import_module("app.main").create_app
        registry_mod = importlib.import_module("app.engines.registry")
        ctx["ENGINES"] = registry_mod.ENGINES
        ctx["Registry"] = registry_mod.Registry
        jobs_mod = importlib.import_module("app.core.jobs")
        ctx["TERMINAL"] = jobs_mod.TERMINAL_JOB_STATUSES
        ctx["JobStore"] = jobs_mod.JobStore
        cost_mod = importlib.import_module("app.core.cost")
        ctx["SpendLog"] = cost_mod.SpendLog
        ctx["cap_reached"] = cost_mod.cap_reached
        keys_mod = importlib.import_module("app.core.keys")
        ctx["KeyStore"] = keys_mod.KeyStore
        ctx["KEYS_FILENAME"] = keys_mod.KEYS_FILENAME
        ctx["PROVIDERS"] = importlib.import_module("app.providers.catalog").PROVIDERS
        ctx["load_platforms"] = importlib.import_module("app.data.specs").load_platforms
        ctx["slugify"] = importlib.import_module("app.core.projects").slugify
    except Exception as exc:
        _fail(f"the app package does not import: {exc}\n{_tail(exc)}")
    # Pin the catalog row the gate runs on (editable config - if the data
    # drifts, this names the row instead of failing obscurely downstream).
    platforms = {(p.id, f.id): f for p in ctx["load_platforms"]() for f in p.formats}
    got = platforms.get(("instagram", "instagram_feed_portrait"))
    if got is None:
        _fail("platforms.json lost the instagram_feed_portrait format this gate pins")
    want = ("image", 1080, 1350, "jpg", 1, 1)
    have = (got.kind, *got.resolution, got.container, got.min_images, got.max_images)
    if have != want:
        _fail(f"platforms.json instagram_feed_portrait: {have} != the pinned {want}")
    # The cap arithmetic this gate pins (core.cost, BUILD_PLAN 4.5): two $0.10
    # calls land exactly on a $0.20 cap; the third call crosses it.
    if ctx["cap_reached"](CAP_USD, ASSET_PRICE_USD, ASSET_PRICE_USD):
        _fail("spending up to exactly the cap must be allowed")
    if not ctx["cap_reached"](CAP_USD, 2 * ASSET_PRICE_USD, ASSET_PRICE_USD):
        _fail("the call crossing the cap must be blocked")
    return f"python {py}; instagram_feed_portrait pinned 1080x1350 jpg; cap math verified"


def check_resume(ctx: dict[str, Any]) -> str:
    """Gate clause 1: restart mid-job, resume on persisted state, no redo.

    App 1 runs a 3-beat portrait job and dies inside beat 2's TTS call (the
    provider blocks forever; the app is abandoned without a clean shutdown).
    The persisted state at that moment: beat 1 done (both assets), beat 2 TTS
    ``generating``, everything else pending. App 2 - a fresh create_app() over
    the SAME projects root - reopens the job engine via resume() and must
    finish the job without redoing beat 1 and without double-counting spend.
    A second job left awaiting_confirmation must NOT be resumed.
    """
    old_tts, old_img = ScriptedTTS(), ScriptedImage()
    app1 = build_app(ctx, "resume-old", old_tts, old_img)
    client1 = client_of(app1)
    try:
        # Beat 2's TTS is the call the "dead" server never returns from.
        blocked = old_tts.block_beat(
            ctx["projects_root"] / slug_of(ctx, PROJECT_RESUME) / "audio" / "beat_02.wav"
        )
        job_a = run_flow(ctx, client1, PROJECT_RESUME, RESUME_BEATS)
        # An unconfirmed job must stay untouched by the restart machinery.
        job_pending = run_flow(ctx, client1, PROJECT_PENDING, RESUME_BEATS, confirm=False)
        if get_job(client1, job_pending)["status"] != "awaiting_confirmation":
            _fail("the unconfirmed job must sit at awaiting_confirmation before the restart")

        wait_for(
            client1,
            job_a,
            lambda p: (
                asset_row(p, "tts", 1)["status"] == "done"
                and asset_row(p, "image", 1)["status"] == "done"
                and asset_row(p, "tts", 2)["status"] == "generating"
            ),
            "reach beat 1 done + beat 2 in flight",
            120.0,
        )
        if not blocked.wait(timeout=10.0):
            _fail("the old engine never entered beat 2's provider call")
        before = get_job(client1, job_a)
        if before["status"] != "running":
            _fail(f"mid-job status must be running, got {before['status']!r}")
        survivors = {
            a["out_path"]: (a["attempts"], a["spent_usd"], Path(a["out_path"]).read_bytes())
            for a in before["assets"]
            if a["status"] == "done"
        }
        if len(survivors) != 2:
            _fail(f"beat 1 must have completed both assets before the restart: {survivors}")

        # --- the restart: app 1 is abandoned exactly like a dead process. Its
        # worker stays blocked inside the provider call; engine.stop() is NEVER
        # called and nothing talks to app1 again - from here it is gone.
        client1 = None

        new_tts, new_img = ScriptedTTS(), ScriptedImage()
        app2 = build_app(ctx, "resume-new", new_tts, new_img)
        client2 = client_of(app2)
        try:
            if get_job(client2, job_a)["status"] != "running":
                _fail(
                    "the persisted job must still be running after the restart - "
                    "the durable state is the whole point"
                )
            resumed = app2.state.jobs.resume()  # the reopen act (app/core/jobs.py)
            if [j.id for j in resumed] != [job_a]:
                _fail(
                    f"resume() must re-enqueue exactly the running job, "
                    f"got {[j.id for j in resumed]}"
                )
            pending_after = get_job(client2, job_pending)
            if pending_after["status"] != "awaiting_confirmation":
                _fail(
                    f"resume() must leave awaiting_confirmation jobs alone, "
                    f"got {pending_after['status']!r}"
                )

            final = wait_for(
                client2,
                job_a,
                lambda p: p["status"] in ctx["TERMINAL"],
                "reach a terminal status after the resume",
                JOB_TIMEOUT_S,
            )
            app2.state.jobs.wait_idle()
            if final["status"] != "completed":
                errors = [a["error"] for a in final["assets"] if a["error"]]
                _fail(f"the resumed job ended {final['status']!r}; asset errors: {errors}")
            if final["spent_usd"] != 0.0:
                _fail(f"the resumed dry-run job must stay at $0, spent {final['spent_usd']}")

            # No asset redone: the old engine completed exactly beat 1's two
            # calls (beat 2's call never returned); the new engine generated
            # exactly the unfinished work - beats 2 and 3 - never beat 1.
            slug = slug_of(ctx, PROJECT_RESUME)
            if sorted(old_tts.completed) != [f"{slug}/beat_01.wav"]:
                _fail(f"the old TTS engine's completed calls moved: {old_tts.completed}")
            if sorted(old_img.completed) != [f"{slug}/beat_01.png"]:
                _fail(f"the old image engine's completed calls moved: {old_img.completed}")
            if f"{slug}/beat_02.wav" not in old_tts.calls:
                _fail(
                    "the old engine never entered beat 2's call - the mid-job "
                    "state was not the one the restart must recover from"
                )
            new_tts_calls = [k.split("/", 1)[1] for k in new_tts.calls if k.startswith(f"{slug}/")]
            new_img_calls = [k.split("/", 1)[1] for k in new_img.calls if k.startswith(f"{slug}/")]
            if new_tts_calls != ["beat_02.wav", "beat_03.wav"]:
                _fail(f"the resumed engine must generate exactly beats 2-3 TTS: {new_tts_calls}")
            if new_img_calls != ["beat_02.png", "beat_03.png"]:
                _fail(f"the resumed engine must generate exactly beats 2-3 images: {new_img_calls}")
            redone = [k for k in new_tts.calls + new_img.calls if k.startswith(f"{slug}/beat_01.")]
            if redone:
                _fail(f"beat 1 was redone after the restart: {redone}")
            for out_path, (attempts, spent, raw) in survivors.items():
                row = next(a for a in final["assets"] if a["out_path"] == out_path)
                if row["status"] != "done" or row["attempts"] != attempts:
                    _fail(
                        f"survivor {out_path} changed: {row['status']} attempts"
                        f" {row['attempts']} (was {attempts})"
                    )
                if row["spent_usd"] != spent:
                    _fail(f"survivor {out_path} spend changed: {row['spent_usd']} (was {spent})")
                if Path(out_path).read_bytes() != raw:
                    _fail(f"survivor artifact changed on disk: {out_path}")
            stuck = asset_row(final, "tts", 2)
            if stuck["status"] != "done" or stuck["attempts"] != 1 or stuck["error"] is not None:
                _fail(f"the stuck generating asset must finish exactly once: {stuck}")

            rows = one_spend_line_per_asset(ctx, slug, final)
            if any(r.get("amount_usd") != 0.0 or r.get("provider_id") != "mock" for r in rows):
                _fail(f"spend log rows must be $0 mock entries: {rows[:2]}")
            return (
                f"restart mid-beat-2 -> resume() on persisted state: beat 1"
                f" untouched (bytes+attempts), beats 2-3 generated once, job"
                f" completed, {len(rows)} spend lines (one per asset), pending"
                f" job not resumed"
            )
        finally:
            app2.state.jobs.stop()
    finally:
        pass  # app1 is the dead server: never stopped, never touched again


def check_retry(ctx: dict[str, Any]) -> str:
    """Gate clause 2: per-asset retry regenerates only the failed asset.

    Beat 2's image fails non-retryably on its first call; the job survives as
    ``partial`` with every other asset done. The BUILD_PLAN 4.4 JSON mutation
    (POST /api/jobs/{id}/assets/{asset_id}/retry) re-queues just that asset;
    the final run is ``completed``, beats 1/3 show exactly one provider call
    each across the whole job with byte-identical artifacts, and all three
    slides are exported.
    """
    tts, image = ScriptedTTS(), ScriptedImage()
    slug = slug_of(ctx, PROJECT_RETRY)
    image.fail_once(ctx["projects_root"] / slug / "visuals" / "beat_02.png")
    app = build_app(ctx, "retry", tts, image)
    client = client_of(app)
    try:
        job_id = run_flow(ctx, client, PROJECT_RETRY, RETRY_BEATS)
        partial = wait_for(
            client,
            job_id,
            lambda p: p["status"] in ctx["TERMINAL"],
            "reach a terminal status",
            JOB_TIMEOUT_S,
        )
        app.state.jobs.wait_idle()
        if partial["status"] != "partial":
            _fail(f"one failed asset must leave the job partial, got {partial['status']!r}")
        want = [
            ("tts", 1, "done"),
            ("image", 1, "done"),
            ("tts", 2, "done"),
            ("image", 2, "failed"),
            ("tts", 3, "done"),
            ("image", 3, "done"),
        ]
        if statuses_of(partial) != want:
            _fail(f"partial run asset states wrong: {statuses_of(partial)}")
        failed = asset_row(partial, "image", 2)
        if not failed["error"] or FAILURE_MESSAGE not in failed["error"]:
            _fail(f"the failed asset must carry the provider error, got {failed['error']!r}")
        survivors = {
            a["out_path"]: Path(a["out_path"]).read_bytes()
            for a in partial["assets"]
            if a["status"] == "done"
        }

        resp = client.post(f"/api/jobs/{job_id}/assets/{failed['id']}/retry")
        if resp.status_code != 200:
            _fail(f"POST retry -> {resp.status_code}: {resp.text[:200]}")
        body = resp.json()
        if body["status"] != "running":
            _fail(f"the retry must re-open the partial job to running, got {body['status']!r}")
        row = next(a for a in body["assets"] if a["id"] == failed["id"])
        if row["error"] is not None or row["status"] not in ("pending", "generating", "done"):
            _fail(f"the retried asset must be re-queued clean, got {row['status']!r}")

        final = wait_for(
            client,
            job_id,
            lambda p: p["status"] in ctx["TERMINAL"],
            "reach a terminal status after the retry",
            JOB_TIMEOUT_S,
        )
        app.state.jobs.wait_idle()
        if final["status"] != "completed":
            errors = [a["error"] for a in final["assets"] if a["error"]]
            _fail(f"the retried job ended {final['status']!r}; errors: {errors}")
        retried = asset_row(final, "image", 2)
        if retried["status"] != "done" or retried["attempts"] != 1 or retried["error"]:
            _fail(f"the retried asset must finish exactly once: {retried}")

        # Only the failed asset was regenerated: beats 1 and 3 keep exactly one
        # provider call each across the whole run; beat 2's image has two.
        tts_calls = [k.split("/", 1)[1] for k in tts.calls if k.startswith(f"{slug}/")]
        if tts_calls != ["beat_01.wav", "beat_02.wav", "beat_03.wav"]:
            _fail(f"TTS calls must be untouched by the retry, got {tts_calls}")
        img_calls = [k.split("/", 1)[1] for k in image.calls if k.startswith(f"{slug}/")]
        if img_calls != ["beat_01.png", "beat_02.png", "beat_03.png", "beat_02.png"]:
            _fail(f"only beat 2's image may be regenerated, got {img_calls}")
        for a in final["assets"]:
            if a["status"] == "done" and a["out_path"] in survivors:
                if Path(a["out_path"]).read_bytes() != survivors[a["out_path"]]:
                    _fail(f"an untouched asset's artifact changed on disk: {a['out_path']}")
        outputs = sorted(p.name for p in (ctx["projects_root"] / slug / "output").glob("*.jpg"))
        if outputs != [f"instagram_feed_portrait_beat_{n:02d}.jpg" for n in (1, 2, 3)]:
            _fail(f"the completed job must export all 3 slides, got {outputs}")
        rows = one_spend_line_per_asset(ctx, slug, final)
        if any(r.get("amount_usd") != 0.0 for r in rows):
            _fail(f"the dry-run retry must stay at $0 per asset: {rows[:2]}")
        return (
            "partial -> JSON retry of the failed image only (beats 1/3: one"
            " call each, bytes unchanged; beat 2: 2nd call) -> completed,"
            " 3 slides exported"
        )
    finally:
        app.state.jobs.stop()


def check_cap(ctx: dict[str, Any]) -> str:
    """Gate clause 3: the hard cap ends the job partial with done assets kept.

    Four image beats at $0.10 each under a $0.20 cap: beats 1-2 finish (the
    spend lands exactly ON the cap - allowed), beats 3-4 are skipped BEFORE
    any paid call with errors naming the cap, the provider is dialed exactly
    twice, the kept beats' deliverables are exported, and the cap + confirmed
    estimate travel into the job payload.
    """
    tts, image = ScriptedTTS(), ScriptedImage(price_usd=ASSET_PRICE_USD)
    slug = slug_of(ctx, PROJECT_CAP)
    app = build_app(ctx, "cap", tts, image)
    client = client_of(app)
    try:
        # The one paid-shaped flow of this gate: dry-run off so the provider's
        # own price quote counts, cap set at the options step, estimate shown
        # and explicitly confirmed (§6.6) before the worker starts.
        job_id = run_flow(
            ctx,
            client,
            PROJECT_CAP,
            CAP_BEATS,
            confirm=False,
            extra_options={"audio": "", "dry_run": "", "spend_cap_usd": f"{CAP_USD:.2f}"},
        )
        payload = get_job(client, job_id)
        if payload["estimate_usd"] != 4 * ASSET_PRICE_USD:
            _fail(
                f"the confirmed estimate must be 4 x {ASSET_PRICE_USD} ="
                f" {4 * ASSET_PRICE_USD}, got {payload['estimate_usd']}"
            )
        if payload["spend_cap_usd"] != CAP_USD:
            _fail(f"the options cap must reach the job, got {payload['spend_cap_usd']}")
        if payload["status"] != "awaiting_confirmation":
            _fail(f"the job must wait for the explicit confirm, got {payload['status']!r}")
        if client.post(f"/jobs/{job_id}/confirm", follow_redirects=False).status_code != 303:
            _fail("confirming the capped job failed")

        final = wait_for(
            client,
            job_id,
            lambda p: p["status"] in ctx["TERMINAL"],
            "reach a terminal status",
            JOB_TIMEOUT_S,
        )
        app.state.jobs.wait_idle()
        if final["status"] != "partial":
            _fail(f"an over-cap job must end partial, got {final['status']!r}")
        want = [
            ("image", 1, "done"),
            ("image", 2, "done"),
            ("image", 3, "skipped"),
            ("image", 4, "skipped"),
        ]
        if statuses_of(final) != want:
            _fail(f"capped run asset states wrong: {statuses_of(final)}")
        if final["spent_usd"] != CAP_USD:
            _fail(f"spending must land exactly on the cap ({CAP_USD}), got {final['spent_usd']}")
        for beat in (1, 2):
            row = asset_row(final, "image", beat)
            if row["status"] != "done" or row["spent_usd"] != ASSET_PRICE_USD:
                _fail(f"kept beat {beat} must be done at ${ASSET_PRICE_USD}: {row}")
        for beat in (3, 4):
            row = asset_row(final, "image", beat)
            if row["spent_usd"] != 0.0 or not row["error"]:
                _fail(f"skipped beat {beat} must carry a cap error at $0: {row}")
            if "spend cap" not in row["error"] or "skipped before paid call" not in row["error"]:
                _fail(f"the skip error must name the cap, got {row['error']!r}")
        dialed = [k.split("/", 1)[1] for k in image.completed if k.startswith(f"{slug}/")]
        if dialed != ["beat_01.png", "beat_02.png"]:
            _fail(f"beats 3-4 must never be dialed, provider completed {dialed}")
        rows = spend_log_rows(ctx, slug)
        if len(rows) != 2:
            _fail(f"the audit trail must carry exactly the 2 paid calls, got {len(rows)}")
        running = 0.0
        for r in rows:
            running += float(r["amount_usd"])
            if running > CAP_USD + 1e-9:
                _fail(f"the running spend crossed the cap: {running} > {CAP_USD}")
            if abs(r["amount_usd"] - ASSET_PRICE_USD) > 1e-9:
                _fail(f"each paid call must cost ${ASSET_PRICE_USD}: {r}")
        outputs = sorted(p.name for p in (ctx["projects_root"] / slug / "output").glob("*.jpg"))
        if outputs != [f"instagram_feed_portrait_beat_{n:02d}.jpg" for n in (1, 2)]:
            _fail(f"the kept beats' deliverables must be exported, got {outputs}")
        return (
            f"cap {CAP_USD:.2f} on ${ASSET_PRICE_USD}/beat: beats 1-2 done at"
            f" exactly {final['spent_usd']:.2f}, beats 3-4 skipped before paid"
            f" call, 2 provider calls, kept deliverables exported, partial"
        )
    finally:
        app.state.jobs.stop()


def check_audit(ctx: dict[str, Any]) -> str:
    """The offline guarantees: guard silent, no keys touched, every persisted
    job in its expected final state, and each job's running spend an exact
    pair of its spend-log audit trail (running-spend display accuracy, 4.5)."""
    guard: SocketGuard = ctx["guard"]
    if guard.violations:
        _fail(
            f"the flow made {len(guard.violations)} outbound network attempt(s):"
            f" {guard.violations[0].splitlines()[0]}"
        )
    for name, store in ctx["key_stores"].items():
        if store.configured_providers():
            _fail(f"this gate must never touch a provider key ({name} store)")
    expected = {
        slug_of(ctx, PROJECT_RESUME): "completed",
        slug_of(ctx, PROJECT_PENDING): "awaiting_confirmation",
        slug_of(ctx, PROJECT_RETRY): "completed",
        slug_of(ctx, PROJECT_CAP): "partial",
    }
    audited = 0
    for db in sorted(ctx["projects_root"].glob("*/state/job.db")):
        slug = db.parent.parent.name
        if slug not in expected:
            _fail(f"unexpected project in the throwaway root: {slug}")
        store = ctx["JobStore"](db)
        jobs = store.list_jobs()
        if len(jobs) != 1 or jobs[0].status != expected[slug]:
            _fail(
                f"{slug}: expected one {expected[slug]!r} job, got"
                f" {[(j.id, j.status) for j in jobs]}"
            )
        log = ctx["SpendLog"](db.parent / "spend_log.jsonl")
        if log.total(job_id=jobs[0].id) != jobs[0].spent_usd:
            _fail(
                f"{slug}: spend log total does not pair exactly with the"
                f" job's running spend ({log.total(job_id=jobs[0].id)} vs"
                f" {jobs[0].spent_usd})"
            )
        audited += 1
    if audited != len(expected):
        _fail(f"expected {len(expected)} persisted projects, found {audited}")
    return (
        f"guard silent ({len(guard.loopback)} harness IPC calls); no keys"
        f" touched; {audited} persisted jobs in expected states, spend log"
        f" pairs exactly with every job's running spend"
    )


